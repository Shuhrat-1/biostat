"""Структурированные сообщения ядра для перевода на фронте.

Каждое сообщение — это код (стабильный идентификатор), параметры для
подстановки и русский текст-фолбэк. Фронтенд по коду собирает перевод
из шаблона; если кода не знает — показывает русский фолбэк.

Так ядро остаётся языконезависимым, а перевод целиком живёт на фронте,
где уже есть система i18n.
"""

from __future__ import annotations

from typing import Any


def msg(code: str, message: str, **params: Any) -> dict[str, Any]:
    """Собрать структурированное сообщение.

    ``code`` — идентификатор для перевода, ``message`` — русский фолбэк
    (уже с подставленными значениями), ``params`` — те же значения
    отдельно, чтобы фронт подставил их в переведённый шаблон.
    """
    return {"code": code, "message": message, "params": params}
