/** Пределы размера входа: вкладка не должна замирать на широком или огромном файле (аудит 03-05). */

/**
 * Сколько колонок рисовать в предпросмотре и в списке колонок. Остальные колонки
 * в расчётах доступны; 50 000 колонок в таблице останавливали страницу на 19 с.
 */
export const MAX_SHOWN_COLUMNS = 200;

/** Файл больше этого не читается: 19 МБ разбираются спокойно, 113 МБ — уже MemoryError. */
export const MAX_FILE_BYTES = 50 * 1024 * 1024;

/** Размер файла для сообщения: «73.4 МБ». */
export function megabytes(bytes: number): string {
  return (bytes / (1024 * 1024)).toFixed(1);
}
