const ESTIMATE_KIND: Record<Lang, Dict> = {
  ru: { mean: "среднее", median: "медиана" },
  en: { mean: "mean", median: "median" },
  pt: { mean: "média", median: "mediana" },
};

/**
 * Имя оценки: «mean_пшеница» → «пшеница — среднее» (аудит 04-02). Только когда
 * после префикса стоит имя группы из результата: mean_diff — не группа.
 */
export function estimateLabel(name: string, groups: unknown, lang: Lang): string {
  const m = /^(mean|median)_(.+)$/.exec(name);
  if (!m || !Array.isArray(groups) || !groups.includes(m[2])) return name;
  return `${m[2]} — ${ESTIMATE_KIND[lang][m[1]]}`;
}

/** Подпись статистики: ключ ядра не меняется, на экране — название (аудит 04-02). */
export function statLabel(key: string, lang: Lang): string {
  const d = STATS[lang];
  if (d.exact[key]) return d.exact[key];
  const part = (x: string) => d.part[x] ?? x;
  const shapiro = /^shapiro_p_(.+)$/.exec(key);
  if (shapiro) return d.tpl.shapiro.replace("{x}", part(shapiro[1]));
  const ci = /^(.+)_ci_(lower|upper)$/.exec(key);
  if (ci) {
    const what = d.exact[ci[1]] ?? part(ci[1]);
    return d.tpl[`ci_${ci[2]}` as "ci_lower"].replace("{x}", what.charAt(0).toUpperCase() + what.slice(1));
  }
  const pre = PREFIX.exec(key);
  if (pre) return d.tpl[pre[1] as "F"].replace("{x}", part(pre[2]));
  const post = /^(.+)_(t|p)$/.exec(key);
  if (post) return d.tpl[post[2] as "t"].replace("{x}", part(post[1]));
  return key;
}

/** Заголовок блока по ключу ядра (с учётом метода, если задан). */
export function extraTitle(key: string, lang: Lang, method?: string): string {
  const specific = method ? METHOD_TITLES[lang][`${method}.${key}`] : undefined;
  return specific ?? TITLES[lang][key] ?? TITLES.ru[key] ?? humanize(key);
}

/** Подпись колонки: перевод частых; короткие сокращения (df, F, sd) как есть. */
export function columnLabel(key: string, lang: Lang): string {
  const known = COLUMNS[lang][key] ?? COLUMNS.ru[key];
  if (known) return known;
  return key.length <= 3 ? key : humanize(key);
}
