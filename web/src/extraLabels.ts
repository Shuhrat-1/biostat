/** «lack_of_fit» → «Lack of fit», «s2_unit» → «S2 unit». */
export function humanize(key: string): string {
  const text = key.replace(/_/g, " ").trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** Один ключ у разных методов значит разное: «метод.ключ» важнее общего. */
const METHOD_TITLES: Record<Lang, Dict> = {
  ru: { "glm_analysis.cells": "Предсказания по ячейкам модели" },
  en: { "glm_analysis.cells": "Predictions by model cell" },
  pt: { "glm_analysis.cells": "Previsões por célula do modelo" },
};

/** Заголовок блока по ключу ядра (с учётом метода, если задан). */
export function extraTitle(key: string, lang: Lang, method?: string): string {
  const specific = method ? METHOD_TITLES[lang][`${method}.${key}`] : undefined;
  return specific ?? TITLES[lang][key] ?? TITLES.ru[key] ?? humanize(key);
}

/** Подпись колонки: перевод частых; короткие сокращения (df, F, sd) как есть. */
export function columnLabel(key: string, lang: Lang): string {
  const known = COLUMNS[lang][key] ?? COLUMNS.ru[key];
  if (known) return known;
  return key.length <= 3 ? key : humanize(key);
}
