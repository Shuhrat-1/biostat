/**
 * Встроенный пример данных для кнопки «Попробовать на примере».
 *
 * Полевой опыт: три сорта × повторности, с числовыми колонками (урожай,
 * высота, площадь) и категориальной (сорт). Позволяет сразу показать
 * сводную статистику, ANOVA по сортам и регрессию высота→урожай.
 *
 * CP1251 не нужен — пример в UTF-8, чтобы работал везде одинаково.
 * Значения с запятой-десятичной, разделитель `;` — заодно демонстрирует
 * автодетекцию европейского формата.
 */

const ROWS: Array<[string, string, string, string]> = [
  // сорт, урожай, высота, площадь (площадь с повторами — не читается как ID)
  ["пшеница", "5,2", "88,4", "120"],
  ["пшеница", "5,5", "90,1", "120"],
  ["пшеница", "5,1", "87,2", "120"],
  ["пшеница", "5,8", "92,0", "115"],
  ["пшеница", "5,3", "89,5", "115"],
  ["пшеница", "4,9", "86,1", "115"],
  ["ячмень", "4,8", "78,3", "100"],
  ["ячмень", "4,6", "76,9", "100"],
  ["ячмень", "5,0", "80,2", "100"],
  ["ячмень", "4,7", "77,5", "95"],
  ["ячмень", "4,5", "75,8", "95"],
  ["ячмень", "4,9", "79,1", "95"],
  ["овёс", "3,9", "70,2", "80"],
  ["овёс", "4,1", "72,0", "80"],
  ["овёс", "3,8", "69,4", "80"],
  ["овёс", "4,0", "71,1", "85"],
  ["овёс", "3,7", "68,5", "85"],
  ["овёс", "4,2", "73,2", "85"],
];

/** Пример как байты — идёт тем же путём разбора, что и загруженный файл. */
export function exampleFileBytes(): Uint8Array {
  const header = "сорт;урожай;высота;площадь";
  const lines = ROWS.map((r) => r.join(";"));
  const text = [header, ...lines].join("\n") + "\n";
  return new TextEncoder().encode(text);
}

