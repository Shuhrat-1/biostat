const DICTS: Record<Lang, Dict> = { ru: RU, en: EN, pt: PT };

export const I18nContext = createContext<Lang>("ru");

/** Хук перевода: t("key") -> строка на текущем языке. */
export function useT(): (key: string) => string {
  const lang = useContext(I18nContext);
  const dict = DICTS[lang];
  return (key: string) => dict[key] ?? DICTS.ru[key] ?? key;
}

/** Текущий язык — для передачи в ядро (локализация методов). */
export function useLang(): Lang {
  return useContext(I18nContext);
}
